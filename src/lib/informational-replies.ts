// ── Индексы и матчинг ────────────────────────────────────────────────────────

const EXACT_INDEX: Map<string, ReplyEntry> = (() => {
  const m = new Map<string, ReplyEntry>();
  for (const entry of ENTRIES) {
    for (const phrase of entry.match) {
      m.set(normalize(phrase), entry);
    }
  }
  return m;
})();

/** Минимальное покрытие для фуззи-совпадения (доля общих токенов фразы/ввода). */
const FUZZY_COVER_THRESHOLD = 0.6;

/**
 * Находит запись по тексту: точное совпадение → консервативный фуззи с
 * защитой от неоднозначности → null. null означает «не распознано» — вызывающий
 * показывает тёплый fallback. Экспортируется для тестов.
 */
export function findInformationalEntry(text: string): ReplyEntry | null {
  const norm = normalize(text);
  if (!norm) return null;

  // 1. Точное совпадение (клик по чипу + короткие канонические перефразировки).
  const exact = EXACT_INDEX.get(norm);
  if (exact) return exact;

  // 2. Фуззи: префиксное совпадение токенов, покрытие ≥ порога, явный лидер.
  const textTokens = new Set(tokens(text));
  if (textTokens.size === 0) return null;

  let best: { entry: ReplyEntry; cover: number } | null = null;
  let secondCover = 0;
  for (const entry of ENTRIES) {
    let entryCover = 0;
    for (const phrase of entry.match) {
      const ptoks = tokens(phrase);
      if (ptoks.length === 0) continue;
      const shared = sharedTokenCount(textTokens, ptoks);
      if (shared === 0) continue;
      // Покрытие — максимум из «доли фразы» и «доли ввода»: короткий точный
      // ввод («что такое сигналы») и длинный prompt оба должны матчиться.
      const cover = Math.max(shared / ptoks.length, shared / textTokens.size);
      if (cover > entryCover) entryCover = cover;
    }
    if (entryCover > (best?.cover ?? 0)) {
      secondCover = best?.cover ?? secondCover;
      best = { entry, cover: entryCover };
    } else if (entryCover > secondCover) {
      secondCover = entryCover;
    }
  }

  if (!best || best.cover < FUZZY_COVER_THRESHOLD) return null;
  // Неоднозначность: если второй кандидат почти вровень — лучше fallback, чем
  // ответить не на тот вопрос (зачем триггеры / зачем интересы).
  if (secondCover >= best.cover - 0.001) return null;
  return best.entry;
}

// Псевдо-случайный выбор варианта. Math.random здесь безопасен — это
// клиентский обработчик отправки, не SSR и не workflow-скрипт.
function pickVariant(replies: string[]): string {
  if (replies.length === 1) return replies[0];
  return replies[Math.floor(Math.random() * replies.length)];
}

/**
 * Ответ на распознанный информационный вопрос, либо null. Вариант ответа
 * выбирается случайно (борьба с однообразием).
 */
export function lookupInformationalReply(text: string): string | null {
  const entry = findInformationalEntry(text);
  return entry ? pickVariant(entry.replies) : null;
}

// Тёплый fallback вместо плоского «Принял… это прототип» — несколько
// вариантов, признаёт вопрос и зовёт к подсказкам, без сухого дисклеймера.
const WARM_FALLBACK: string[] = [
  "Понял вопрос. Свободные формулировки я ещё осваиваю — а пока самое быстрое рядом, в подсказках под строкой.",
  "Принял. Полный ответ дам, когда подключим живой диалог; сейчас загляните в подсказки под строкой — там основное.",
  "Хороший вопрос. Над свободным текстом я пока учусь — подскажу через кнопки-подсказки ниже.",
];

/** Тёплый, варьируемый ответ на нераспознанный свободный текст. */
export function warmFallbackReply(): string {
  return pickVariant(WARM_FALLBACK);
}

