/**
 * Подсказки для шагов мастера guided-signal (1–8). В этой модели wizard'а
 * чипы — это **вопросы**, не действия в интерфейсе: каждый ask-чип попадает
 * в чат-историю текущего раздела и тянет ответ ассистента в раскрытый
 * drawer. Ветви по под-состояниям меняют формулировку вопроса.
 */

import type { SuggestionItem, WizardSub } from "./types";

function ask(id: string, label: string, prompt: string): SuggestionItem {
  return { id, label, action: { kind: "ask", prompt } };
}

// ─── Step 1 — выбор сценария ────────────────────────────────────────────────
// Раньше дублировали 6 карточек сценариев из основного экрана. Сейчас два
// вопроса по сути решения: «в чём разница» и «что выбрать».
const STEP_1: SuggestionItem[] = [
  ask(
    "wiz-1-diff",
    "В чём разница между категориями?",
    "В чём разница между категориями сценариев? Кратко по каждой."
  ),
  ask(
    "wiz-1-which",
    "Какую мне сейчас выбрать?",
    "Какую категорию сценария мне стоит выбрать в моей ситуации?"
  ),
];

// ─── Step 2 — интересы и триггеры ───────────────────────────────────────────
function step2(s: { hasInterests: boolean; hasDomains: boolean }): SuggestionItem[] {
  if (!s.hasInterests && !s.hasDomains) {
    return [
      ask("wiz-2-where-start", "С чего начать?", "С чего лучше начать настраивать интересы и триггеры?"),
      ask("wiz-2-where-take", "Откуда вы берёте интересы?", "Откуда вы берёте интересы — что подсказывает AI?"),
      ask("wiz-2-what-trigger", "Что такое триггер?", "Что такое триггер и чем он отличается от интереса?"),
    ];
  }

  if (s.hasInterests && s.hasDomains) {
    return [
      ask("wiz-2-narrow-q", "Стоит ли сузить набор?", "Мне сузить набор интересов и триггеров?"),
      ask("wiz-2-widen-q", "Можно ли расширить охват?", "Стоит ли мне расширить охват — добавить интересы и триггеры?"),
      ask("wiz-2-quality", "Этот набор подойдёт?", "Подойдёт ли мне такой набор интересов и триггеров?"),
    ];
  }

  if (s.hasInterests) {
    return [
      ask("wiz-2-need-trigger", "Зачем триггеры?", "Зачем добавлять триггеры, если интересы уже есть?"),
      ask("wiz-2-which-domains", "Какие домены выбрать?", "Какие домены стоит добавить как триггеры?"),
      ask("wiz-2-without-trigger", "Можно ли без триггеров?", "Можно ли запустить сигнал без доменов-триггеров?"),
    ];
  }

  return [
    ask("wiz-2-need-interests", "Зачем интересы?", "Зачем добавлять интересы, если домены уже выбраны?"),
    ask("wiz-2-which-interests", "Какие интересы подойдут?", "Какие интересы подойдут к моим триггерам?"),
    ask("wiz-2-overlap", "Не пересекаются ли они?", "Не будут ли интересы пересекаться с моими доменами?"),
  ];
}

// ─── Step 3 — база ──────────────────────────────────────────────────────────
const STEP_3: SuggestionItem[] = [
  ask("wiz-3-format", "Какие форматы базы?", "Какие форматы файлов с базой вы принимаете?"),
  ask("wiz-3-required-fields", "Какие поля обязательны?", "Какие поля должны быть в файле базы?"),
  ask("wiz-3-no-base", "А если базы нет?", "Что делать, если у меня пока нет базы клиентов?"),
];

// ─── Step 4 — объём ─────────────────────────────────────────────────────────
const STEP_4: SuggestionItem[] = [
  ask("wiz-4-volume-why", "От чего зависит объём?", "От чего зависит рекомендуемый объём аудитории?"),
  ask("wiz-4-volume-max", "Можно поставить максимум?", "Что будет, если я поставлю максимально возможный объём?"),
  ask("wiz-4-volume-test", "А минимальный?", "Какой минимальный объём имеет смысл для теста?"),
];

// ─── Step 5 — бюджет ────────────────────────────────────────────────────────
// Раньше был dispatch budget_help_shown с inline-маскотом под инпутом; теперь —
// обычный ask, ответ приходит в чат-историю раздела.
const STEP_5: SuggestionItem[] = [
  ask(
    "wiz-5-budget-why",
    "Как рассчитывается бюджет?",
    "Как рассчитывается рекомендуемый бюджет?"
  ),
  ask("wiz-5-budget-conservative", "Можно поменьше?", "Что будет, если я поставлю бюджет меньше рекомендуемого?"),
  ask("wiz-5-budget-aggressive", "Можно побольше?", "Имеет ли смысл ставить бюджет больше рекомендуемого?"),
];

// ─── Step 6 — имя сигнала ───────────────────────────────────────────────────
function step6(s: { nameSet: boolean }): SuggestionItem[] {
  if (s.nameSet) {
    return [
      ask("wiz-6-rename-q", "Поменять название?", "Стоит ли мне поменять название сигнала?"),
      ask("wiz-6-edit-q", "Что-нибудь править?", "Что-нибудь стоит подправить в параметрах перед запуском?"),
    ];
  }
  return [
    ask("wiz-6-name-q", "Как назвать сигнал?", "Как лучше назвать этот сигнал?"),
    ask("wiz-6-edit-q2", "Что-нибудь править?", "Что-нибудь стоит подправить в параметрах?"),
  ];
}

// ─── Step 7 — запуск ────────────────────────────────────────────────────────
const STEP_7: SuggestionItem[] = [
  ask("wiz-7-launch-when", "Когда запускать?", "Когда лучше запустить — сразу или отложить?"),
  ask("wiz-7-after-launch", "Что будет после запуска?", "Что произойдёт после запуска сигнала?"),
  ask("wiz-7-can-pause", "Смогу ли я остановить?", "Смогу ли я остановить сигнал после запуска?"),
];

// ─── Step 8 — результат ─────────────────────────────────────────────────────
const STEP_8: SuggestionItem[] = [
  ask("wiz-8-next", "Что дальше?", "Что мне делать дальше с этим сигналом?"),
  ask("wiz-8-campaign", "Когда делать кампанию?", "Когда нужно делать кампанию на этом сигнале?"),
  ask("wiz-8-stats", "Где смотреть результат?", "Где смотреть результаты по этому сигналу?"),
];

export function resolveWizardStep(s: WizardSub): SuggestionItem[] {
  switch (s.step) {
    case 1: return STEP_1;
    case 2: return step2({ hasInterests: s.hasInterests, hasDomains: s.hasDomains });
    case 3: return STEP_3;
    case 4: return STEP_4;
    case 5: return STEP_5;
    case 6: return step6({ nameSet: s.nameSet });
    case 7: return STEP_7;
    case 8: return STEP_8;
  }
}
